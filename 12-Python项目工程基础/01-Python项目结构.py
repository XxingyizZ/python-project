# Python项目结构

# 单个.py文件可以是一个简单的Python程序。
# 当代码越来越多时，可以使用目录和多个文件组织代码。
# 一组具有明确用途的代码文件，可以组成一个Python项目。

# 一个简单的项目目录：
# my_project/
# ├── main.py
# ├── utils.py
# └── data/

# main.py通常作为程序的主要入口。
# utils.py可以保存一些可复用的功能代码。
# data/目录可以保存项目需要的数据文件。

# 项目结构的作用：
# 1. 不同功能放在不同文件中，代码更容易查找。
# 2. 项目变大后更容易维护。
# 3. 多人协作时更容易分工。

# 前面学习过，一个.py文件可以作为一个模块使用。
# import utils

# .py文件        → 模块
# 多个模块、数据和配置 → 项目

# 初学阶段不需要设计复杂的项目结构。
# 应该先保持结构简单，随着项目复杂度增加再逐步扩展。
