#python中变量的命名规则：
# 1.变量名只能包含字母、数字和下划线，且不能以数字开头
# 2.变量名不能使用 Python 的关键字或保留常量，例如 if、else、for、while、True、False、None 等
# 3.变量名严格区分大小写
# 4.变量名应该具有描述性，能够清楚地表达变量的含义；多个部分使用下划线连接；英文字母全部小写