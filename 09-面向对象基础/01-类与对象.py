# 类与对象
# 类可以理解为创建某类对象的描述或模板，对象是根据类创建出来的具体实例。

# 使用class关键字定义类。
# class Student:
#     pass

# 调用类可以创建对象。
# student1 = Student()
# student2 = Student()

# Student是类，student1和student2是根据Student类创建的对象。
# 一个类可以创建多个对象，不同对象彼此独立。

# 定义类和创建对象的基本流程：
# 定义类
#     ↓
# 调用类
#     ↓
# 创建对象
#
# class Student:
#     pass
#
# student = Student()

# Student()在这里表示创建一个Student对象，不是普通的业务函数调用。
