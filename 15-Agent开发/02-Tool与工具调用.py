# Tool与工具调用

# Tool是Agent可以调用的外部能力。
# 例如：计算器、天气查询、搜索、数据库查询和文件读取。
# 本章只使用安全、简单的纯Python工具。

# LLM主要负责理解、推理和生成。
# 工具可以帮助程序进行计算、查询或处理数据。

# Tool Calling不是让模型直接执行Python函数。
# 更准确的流程是：
# LLM产生工具调用请求
#       ↓
# Python程序读取工具名称和参数
#       ↓
# Python执行对应函数
#       ↓
# Python把工具结果返回给LLM

# 工具调用示意：
# 用户：帮我计算10加20。
# LLM：请求调用add工具。
# Python：执行add(10, 20)，得到30。
# LLM：根据30生成最终回答。

# 工具能做什么，取决于Python程序明确提供了什么能力。
# 不应该让模型任意执行Python代码或系统命令。
