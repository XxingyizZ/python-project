# LLM与大语言模型基础

# LLM是Large Language Model的缩写，中文通常称为大语言模型。
# LLM可以根据输入的内容生成文本等结果。

# LLM可以完成一些常见任务：
# 问答、总结、改写、分类、信息提取和代码生成。

# 一个LLM应用通常由下面几部分组成：
# LLM + Python程序 + 用户输入 + 业务逻辑

# LLM服务通常会提供API。
# Python程序可以通过HTTP或官方SDK调用LLM服务。
# LLM服务 → API → Python程序

# LLM API本质上仍然是程序与外部服务之间的数据交换。
# 基本流程是：发送输入 → 模型生成结果 → 返回响应。

# 本章学习如何使用已经训练好的模型。
# 当前不学习Transformer数学原理、模型训练、微调、RLHF或GPU训练。
