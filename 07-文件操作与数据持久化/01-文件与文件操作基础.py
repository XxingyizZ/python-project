# 文件与文件操作基础
# 文件可以保存数据，让数据在程序结束后继续存在。
# list、tuple、dict和set主要用于组织程序运行期间的数据。
# 文件可以把数据保存到程序运行之外，这是一种常见的数据持久化方式。

# 程序运行期间的数据通常保存在内存中，程序结束后数据可能消失。
# 数据写入文件后，程序下次运行时还可以重新读取。

# open()用于打开文件。
# 基本形式：open(文件路径, 打开模式)
# file = open("test.txt", "r")

# r表示读取文件。
# file = open("test.txt", "r")

# w表示写入文件。如果文件已经存在，原有内容会被覆盖。
# file = open("test.txt", "w")

# a表示追加写入，在原有内容后继续写入，不会覆盖原有内容。
# file = open("test.txt", "a")

