# json模块
# Python标准库提供了json模块，用来处理JSON数据。
# 使用前需要先导入json模块。
# import json

# JSON数据通常需要先转换成Python对象，才能交给Python程序处理。
# Python程序处理完成后，也可以再转换成JSON数据。

# JSON和Python数据类型的基本对应关系：
# JSON object  → Python dict
# JSON array   → Python list
# JSON string  → Python str
# JSON number  → Python int或float
# JSON true    → Python True
# JSON false   → Python False
# JSON null    → Python None

# json模块主要使用dumps、loads、dump和load处理JSON数据。
# 这些名称和作用将在后续内容中分别学习。
