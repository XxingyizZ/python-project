# JSON基础
# JSON是一种常见的数据交换格式，适合在不同程序之间传递结构化数据。
# JSON不是Python语法，但它的写法和Python中的字典、列表有相似之处。

# JSON对象可以表示一组键值对。
# {
#     "name": "小明",
#     "age": 18,
#     "score": 90
# }

# JSON中的对象类似于Python字典，数组类似于Python列表。
# JSON中的字符串使用双引号。

# JSON支持的常见数据类型：
# object：对象
# array：数组
# string：字符串
# number：数字
# true：真
# false：假
# null：空值

# JSON中的true、false、null要使用小写，和Python中的True、False、None写法不同。
# JSON object不是Python字典，JSON array也不是Python列表，只是数据形式比较相似。
