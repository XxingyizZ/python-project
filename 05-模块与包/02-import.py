# import
# import用于导入模块。
# 基本语法：import 模块名

# 导入标准库中的math模块。
# import math
# print(math.pi)
# print(math.sqrt(16))

# 通过模块名.名称可以访问模块中的变量或函数。
# import math
# result = math.sqrt(25)
# print(result)

# random也是Python标准库中的模块，可以生成随机数据。
# import random
# number = random.randint(1, 10)
# print(number)

# 可以同时导入多个模块，但当前示例主要使用一个模块进行说明。
# import math
# import random

# import的作用是导入模块，不是把代码简单复制到当前文件中。
# 模块名可以帮助区分不同模块中的同名名称。

# Python中的import与C语言中的#include有相似的使用目的，
# 但两者机制不同：#include主要是预处理阶段的文本或声明包含，
# import是Python的模块导入机制。
